// Caracteres fuera del juego latino ampliado: senal de copy corrupto
// (CJK, cirilico, fullwidth). Un solo caso asi arruina una pagina.
const BAD_CHARS = /[\u2E80-\u9FFF\uAC00-\uD7AF\uFF00-\uFFEF\u0400-\u04FF]/;

function validate(entry, catalogue, onDisk, errors, warnings, slugs, batch) {
  const at = entry.slug;
  const fail = (m) => errors.push(`${at}: ${m}`);
  const warn = (m) => warnings.push(`${at}: ${m}`);

  if (slugs.has(at)) fail('slug duplicado');
  slugs.add(at);
  // Re-ejecucion: el script debe poder sobrescribir SU propia salida (build en
  // tres pasadas). Solo se niega a pisar un archivo que no lleve la marca de
  // generacion, que seria una pagina escrita a mano.
  if (onDisk.has(at)) {
    const existing = fs.readFileSync(path.join(TOOLS_DIR, `${at}.html`), 'utf8');
    if (existing.includes(GEN_MARKER)) warn('se regenera (ya lo genero este script)');
    else fail('ya existe tools/' + at + '.html y NO lleva la marca de generacion — no se pisa a mano');
  }
  if (!/^[a-z0-9]+(-[a-z0-9]+)*$/.test(at)) fail('slug no kebab-case');

  if (!/^https:\/\//.test(entry.embed?.url || '')) fail('la URL del embed debe ser https');
  if (entry.lang !== 'en' && entry.lang !== 'es') fail('lang debe ser en|es');

  const tl = entry.title.length;
  if (tl < 25 || tl > 70) fail(`title tiene ${tl} caracteres (se esperan 25-70)`);
  const dl = entry.description.length;
  if (dl < 110 || dl > 175) fail(`description tiene ${dl} caracteres (se esperan 110-175)`);

  if (!entry.h1) fail('falta h1');
  if (!entry.lede) fail('falta lede');
  if (!entry.tldr) fail('falta tldr (bloque de respuesta directa para GEO)');

  const kw = (entry.keywords || '').split(',').map((s) => s.trim()).filter(Boolean);
  if (kw.length < 8) fail(`solo ${kw.length} keywords (minimo 8)`);
  kw.forEach((k) => {
    if (BAD_CHARS.test(k)) fail(`keyword corrupta: "${k}"`);
  });

  const secs = entry.sections || [];
  if (secs.length < 3) fail(`${secs.length} secciones (minimo 3)`);
  secs.forEach((s, i) => {
    if (!s.h2) fail(`seccion ${i + 1} sin h2`);
    if (!(s.paras || []).length) fail(`seccion ${i + 1} sin parrafos`);
  });

  const faq = entry.faq || [];
  if (faq.length < 4) fail(`${faq.length} preguntas de FAQ (minimo 4)`);
  faq.forEach((f, i) => {
    if (!f.q || !f.a) fail(`FAQ ${i + 1} incompleta`);
  });

  if (!entry.apps?.length && !entry.book) fail('sin app ni libro: dead end de venta');

  // Productos: deben existir en el catalogo derivado de apps-data.js
  (entry.apps || []).forEach((id) => {
    if (!(catalogue.products.apps || []).some((a) => a.id === id)) fail(`app id "${id}" no existe en el catalogo`);
  });
  if (entry.book && !(catalogue.products.books || []).some((b) => b.id === entry.book)) {
    fail(`book id "${entry.book}" no existe en el catalogo`);
  }
  // Categoria: debe existir en los angulos de venta de build-tool-funnels.
  // Aviso y no error, porque el orden de build es circular por naturaleza:
  // build-tool-funnels exige que el HTML exista, y este script exige el
  // catalogo. Ver "ORDEN DE BUILD" mas abajo.
  if (!(catalogue.angles || {})[entry.category]) {
    warn(`categoria "${entry.category}" aun no esta en data/tool-funnels.json (ejecuta build-tool-funnels.mjs y repite)`);
  }

  // Copy corrupto en cualquier sitio
  const all = JSON.stringify(entry);
  const bad = all.match(BAD_CHARS);
  if (bad) fail(`caracteres no latinos en el copy: ${[...new Set(bad)].join(' ')}`);

  // Long-tail: cada objetivo debe aparecer REALMENTE en el texto de la pagina.
  // Sin esto, "apuntar a keywords" es una declaracion de intenciones: nadie
  // comprueba que la pagina hable de lo que dice hablar.
  const targets = entry.targets || [];
  if (targets.length < 5) fail(`solo ${targets.length} long-tail targets (minimo 5)`);
  // OJO: se busca sobre la entrada SIN `targets`. Si se buscara sobre `all`,
  // el propio array de objetivos estaria dentro del texto y el chequeo pasaria
  // siempre, porque cada frase se encuentra a si misma. Guardian circular.
  const { targets: _targets, ...copyOnly } = entry;
  const pageText = JSON.stringify(copyOnly).toLowerCase();
  targets.forEach((t) => {
    const words = t
      .toLowerCase()
      .split(/[^a-z0-9ñáéíóúü]+/)
      .filter((w) => w.length >= 4 && !STOPWORDS.has(w));
    if (!words.length) return;
    const missing = words.filter((w) => !pageText.includes(w));
    if (missing.length) {
      fail(`long-tail "${t}" no cubierto en el copy (faltan: ${missing.join(', ')})`);
    }
  });

  // Enlaces internos rotos (mata el SEO mas de lo que parece).
  // OJO 1: `all` viene de JSON.stringify, asi que las comillas van escapadas
  // como \". Un regex href=" aqui NO casa nunca y el check pasa en verde
  // sin comprobar nada. Hay que aceptar ambas formas.
  // OJO 2: se resuelve con path.resolve sobre el directorio de la pagina
  // (ROOT/tools). Quitar "../" a mano convertia ../books/x.html en
  // tools/books/x.html y daba por roto lo que esta perfectamente bien.
  const hrefs = [...all.matchAll(/href=\\?"([^"\\]+)\\?"/g)].map((m) => m[1]);
  hrefs.forEach((h) => {
    if (/^(https?:|#|mailto:)/.test(h)) return;
    // Los enlaces entre las 9 paginas de este mismo lote no existen todavia
    // en la primera pasada: se generan en este mismo script.
    const sibling = h.replace(/\.html$/, '');
    if (batch.has(sibling)) return;
    const target = path.resolve(TOOLS_DIR, h.split('#')[0]);
    if (!fs.existsSync(target)) fail(`enlace interno roto: ${h}`);
  });
}

