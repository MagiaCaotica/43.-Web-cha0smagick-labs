function renderLd(entry, ctx) {
  const t = L[entry.lang];
  const url = `${SITE}/tools/${entry.slug}.html`;
  const app = ctx.app || null;
  const book = ctx.book || null;

  const graph = [
    {
      '@type': 'WebApplication',
      '@id': `${url}#tool`,
      name: entry.name,
      url,
      description: entry.description,
      inLanguage: entry.lang,
      applicationCategory: APP_CATEGORY[entry.category] || 'UtilitiesApplication',
      operatingSystem: 'Any modern web browser',
      browserRequirements: 'Requires JavaScript',
      isAccessibleForFree: true,
      featureList: (entry.compare || []).filter((c) => c.free).map((c) => c.feature),
      offers: { '@type': 'Offer', price: '0', priceCurrency: 'USD', availability: 'https://schema.org/InStock' },
      publisher: { '@id': `${SITE}/#organization` },
      mainEntityOfPage: { '@type': 'WebPage', '@id': url }
    },
    {
      '@type': 'BreadcrumbList',
      itemListElement: [
        { '@type': 'ListItem', position: 1, name: 'Cha0smagick Labs', item: `${SITE}/` },
        { '@type': 'ListItem', position: 2, name: t.navTools, item: `${SITE}/tools/` },
        { '@type': 'ListItem', position: 3, name: entry.h1, item: url }
      ]
    },
    {
      '@type': 'Organization',
      '@id': `${SITE}/#organization`,
      name: 'Cha0smagick Labs',
      url: SITE,
      description: 'Corporate Cybermancy Solutions. Free occult tools, Android apps and PDF books.'
    }
  ];

  // App remunerada. SIN aggregateRating: inventar un numero de reseñas es
  // falsificar un dato y es motivo de accion manual en Busquedas Enrichidas.
  if (app) {
    graph.push({
      '@type': 'SoftwareApplication',
      '@id': `${url}#app`,
      name: app.name,
      applicationCategory: 'GameApplication',
      operatingSystem: 'Android',
      description: `Premium Android app related to ${entry.name}.`,
      offers: { '@type': 'Offer', price: money(app.price).replace(/[^0-9.]/g, ''), priceCurrency: 'USD', availability: 'https://schema.org/InStock' },
      installUrl: app.url,
      publisher: { '@id': `${SITE}/#organization` }
    });
  }

  if (book) {
    graph.push({
      '@type': 'Book',
      '@id': `${url}#book`,
      name: book.name,
      author: { '@id': `${SITE}/#organization` },
      inLanguage: book.language || entry.lang,
      url: `${SITE}/books/${book.id}.html`,
      offers: { '@type': 'Offer', price: money(book.price).replace(/[^0-9.]/g, ''), priceCurrency: 'USD', availability: 'https://schema.org/InStock' }
    });
  }

  const faq = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    mainEntity: entry.faq.map((f) => ({
      '@type': 'Question',
      name: f.q,
      acceptedAnswer: { '@type': 'Answer', text: f.a }
    }))
  };

  return `    <script type="application/ld+json">
${JSON.stringify({ '@context': 'https://schema.org', '@graph': graph }, null, 4)}
    </script>
    <script type="application/ld+json">
${JSON.stringify(faq, null, 4)}
    </script>`;
}

// Tabla de datos. Reutiliza .compare-table, que ya existe en css/style.css.
// Para GEO es la parte mas rentable del articulo: una tabla se extrae entera
// y se cita, mientras que un parrafo largo se resume o se descarta.
function renderTable(t) {
  const out = ['            <table class="compare-table">'];
  if (t.caption) out.push(`                <caption>${t.caption}</caption>`);
  out.push('                <thead><tr>' + t.head.map((h) => `<th>${h}</th>`).join('') + '</tr></thead>');
  out.push('                <tbody>');
  t.rows.forEach((r) => out.push('                    <tr>' + r.map((c) => `<td>${c}</td>`).join('') + '</tr>'));
  out.push('                </tbody>');
  out.push('            </table>');
  return out.join('\n');
}

