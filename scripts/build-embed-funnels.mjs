function main() {
  if (!fs.existsSync(CATALOG_FILE)) {
    console.error('FALLO: falta data/tool-funnels.json. Ejecuta primero:');
    console.error('  node scripts/build-tool-funnels.mjs');
    process.exit(1);
  }
  const catalogue = JSON.parse(fs.readFileSync(CATALOG_FILE, 'utf8'));

  const onDisk = new Set(
    fs.readdirSync(TOOLS_DIR).filter((f) => f.endsWith('.html') && f !== 'index.html').map((f) => f.replace(/\.html$/, ''))
  );

  const errors = [];
  const warnings = [];
  const slugs = new Set();
  // El lote completo, no el recorrido: los enlaces entre estas 9 paginas son
  // validos aunque la hermana se valide despues en la misma pasada.
  const batch = new Set(EMBED_TOOLS.map((e) => e.slug));
  EMBED_TOOLS.forEach((e) => validate(e, catalogue, onDisk, errors, warnings, slugs, batch));

  if (errors.length) {
    console.error('\nFALLO de validacion:\n' + errors.map((e) => '  - ' + e).join('\n') + '\n');
    process.exit(1);
  }

  const written = [];
  EMBED_TOOLS.forEach((entry) => {
    const app = entry.apps?.length
      ? (catalogue.products.apps || []).find((a) => a.id === entry.apps[0])
      : null;
    const book = entry.book ? (catalogue.products.books || []).find((b) => b.id === entry.book) : null;
    const html = renderPage(entry, { app, book });
    fs.writeFileSync(path.join(TOOLS_DIR, `${entry.slug}.html`), html, 'utf8');
    written.push({ slug: entry.slug, lang: entry.lang, app: app?.name || null, book: book?.name || null });
  });

  console.log('OK  9 paginas de embed generadas en tools/');
  written.forEach((w) => {
    console.log(`    ${w.slug.padEnd(24)} ${w.lang}  ${w.app ? 'app: ' + w.app : '—'}${w.book ? '  |  libro: ' + w.book : ''}`);
  });

  const missingAngles = Object.keys(CATEGORY_ADDENDUM).filter((c) => !catalogue.angles[c]);
  if (missingAngles.length) {
    console.log(`\n  AVISO: estas categorias aun no estan en data/tool-funnels.json:`);
    console.log('    ' + missingAngles.join('\n    '));
  }
  if (warnings.length) {
    console.log(`\n  AVISO (${warnings.length}):`);
    warnings.forEach((w) => console.log('    - ' + w));
  }

  console.log('\n  ORDEN DE BUILD (el primer ciclo necesita las tres pasadas):');
  console.log('    1. node scripts/build-embed-funnels.mjs   <- genera los 9 HTML');
  console.log('    2. node scripts/build-tool-funnels.mjs   <- los da de alta en el catalogo');
  console.log('    3. node scripts/build-embed-funnels.mjs   <- reescribe con precios del catalogo');
  console.log('\n  PENDIENTE MANUAL (no lo hace este script):');
  console.log('    node scripts/add-embed-funnels-index.mjs   (sitemap.xml + tarjetas en tools/index.html)');
}

main();